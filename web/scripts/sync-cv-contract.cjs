// Keep the browser's pure CV contract aligned with the API without importing
// server modules outside Next's workspace or changing the Docker build context.
const fs = require('node:fs');
const path = require('node:path');
const target = path.join(__dirname, '../src/lib/cv-contract');
fs.mkdirSync(target, { recursive: true });
for (const name of ['cv-document.ts', 'cv-document-render.ts', 'cv-template-catalog.ts']) {
  const source = path.join(__dirname, '../../src/career', name);
  const destination = path.join(target, name);
  if (!fs.existsSync(source)) {
    if (!fs.existsSync(destination)) throw new Error(`Missing generated CV contract: ${name}`);
    continue; // Standalone frontend Docker builds use the checked-in generated contract.
  }
  const content = '// Generated by scripts/sync-cv-contract.cjs. Edit src/career/' + name + ' in the repository root.\n' + fs.readFileSync(source, 'utf8');
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(destination, 'utf8') !== content) throw new Error(`CV contract is stale: ${name}`);
  } else fs.writeFileSync(destination, content);
}
